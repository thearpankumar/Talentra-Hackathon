#!/usr/bin/env python
"""Build docs/13_rbac_matrix.xlsx from the staging model.   usage: python docs/tools/build_rbac.py"""
import os, sys, re
from collections import Counter, defaultdict
sys.path.insert(0, os.path.dirname(__file__))
import xl
import rbac_spec as S
import rbac_core as C
import rbac_text as X
from rbac_tests import TESTS
from openpyxl.styles import PatternFill, Font, Alignment
from openpyxl.formatting.rule import FormulaRule
from openpyxl.utils import get_column_letter

OUT = os.path.join(C.ROOT if hasattr(C, "ROOT") else os.path.join(os.path.dirname(__file__), "..", ".."), "docs", "13_rbac_matrix.xlsx")
OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "13_rbac_matrix.xlsx"))
SENS_RANK = {"Public": 0, "Internal": 1, "Personal": 2, "Sensitive": 3}


def stats():
    model, T, rows = C.compute()
    results = C.validate(model, T, rows)
    return model, T, rows, results


def views_over(model):
    d = defaultdict(list)
    for v in model["views"]:
        for t in v.get("tables") or []:
            d[t].append(v["name"])
    return d


def masked_expr(col):
    dom, t = col.get("domain"), col.get("type", "")
    if dom == "email": return "regexp_replace({c}, '^(.).*(@.*)$', '\\1***\\2')"
    if dom == "phone": return "'*****' || right({c}, 3)"
    if dom == "person_name": return "left({c}, 1) || '***'"
    if dom == "date": return "date_trunc('year', {c})::DATE"
    return "NULL"


def main():
    model, T, rows, results = stats()
    V = views_over(model)
    # ---------------- RoleMatrix
    hdr = ["table", "module", "kind", "delete_policy", "volume", "max_sensitivity", "personal_cols", "sensitive_cols", "owner_scope", "rule_id",
           "grant_class", "views_over_table"] + S.ACTORS
    mrows = []
    for n, t in T.items():
        r = rows[n]
        sens = max((c["sens"] for c in t["columns"]), key=lambda s: SENS_RANK[s])
        mrows.append([n, t["module"], t["kind"], t["delete_policy"], t.get("volume", ""), sens,
                      sum(1 for c in t["columns"] if c["sens"] == "Personal"), sum(1 for c in t["columns"] if c["sens"] == "Sensitive"),
                      r["owner"], r["rule"], r["gclass"], ", ".join(V.get(n, []))] + [r["cells"][a] for a in S.ACTORS])
    mrows.sort(key=lambda x: (x[1], x[0]))
    wb = xl.new_wb()

    # ---------------- Legend
    legend = [
        ["Purpose", "Role-based access matrix for the Talentra schema (docket section 3; B78/B79). One row per table (RoleMatrix), derived by an explicit rule set (sheet Rules) plus per-table groups. Generated by docs/tools/build_rbac.py from docs/_staging/*.yaml; do not edit by hand."],
        ["Cell grammar", "<letters>[*]|<enforcement code>.  Letters: C create (INSERT), R read (SELECT), U update, D delete (on soft entities D = soft delete via UPDATE deleted_at). '-' = no access (default deny)."],
        ["Scope mark *", "Scoped access: own rows / own tenant (organisation_id) / mapped organisations / own campus / published rows only. A cell without * on private data is reserved for staff and service roles."],
        ["G", "DB grant to a SQL role (service tier or persona pool role). Denials by absence of a grant are also G."],
        ["V", "Restricted view or SQL function with the predicate baked in (vw_* ; masked projections); the base table is not granted to that actor."],
        ["A", "Application layer check (permission catalogue, data_scope predicate, workflow). Also used for '-' cells of human actors: the permission does not exist."],
        ["T", "Transaction or declarative constraint (composite FK, CHECK, partial UNIQUE, FOR UPDATE txn) enforces the rule even if the application is wrong."],
        ["N", "Not applicable: backup_operator (database-level BACKUP privilege, not a table grant) and migration_owner (DDL/owner window; data DML only for seeds)."],
        ["Combined codes", "Joined with '+', strongest first: V+A = reads through a view and writes/predicates in the app; T+A = constraint plus app check."],
        ["Human actors", "super_admin, admin, account_admin, guest, candidate, employer, recruiter, consultant, placement_officer (docket section 3). End users are NOT SQL users: they are mapped to persona pool roles (E-01)."],
        ["Service roles", "app_service (= app_rw), auth_svc, billing_svc, audit_writer, purge_svc, compliance_svc, etl_service, analytics_reader, audit_reader, backup_operator, migration_owner. The first six sub-divide the 'app tier' so that secrets, money, audit and compliance data have separate blast radii."],
        ["app_service rule", "Union of what the human personas may do on the table (so workers can serve every persona) plus system writes (CRU, CR when append-only). Never wider; tier-restricted tables (auth, money, vault, compliance, analytics) are excluded or read-only."],
        ["Append-only", "No actor holds U or D on delete_policy = append_only tables. Row-level TTL is the only deleter and runs as a system job. See sheet Validation."],
        ["Assumptions", "CockroachDB v26.2 PG dialect; no column-level GRANT; RLS/triggers/SECURITY DEFINER not relied upon; viewer context is an explicit viewer argument (function/prepared statement), not a custom session variable (F-05). Gig workers are candidate personas (F-13)."],
        ["Counts", f"{len(T)} tables, {len(S.ACTORS)} actors, {len(T) * len(S.ACTORS)} cells, {sum(1 for t in T.values() if t['delete_policy']=='append_only')} append-only tables."],
    ]
    xl.add_sheet(wb, "Legend", ["item", "meaning"], legend, widths=[18, 150], wrap_cols=("meaning",))

    # ---------------- Actors
    xl.add_sheet(wb, "Actors", ["actor", "kind", "definition", "how identified", "DB connection identity", "CockroachDB SQL role mapping", "data scope", "privileged-action constraints"],
                 X.ACTOR_ROWS, widths=[18, 16, 55, 60, 28, 60, 50, 55], wrap_cols=("definition", "how identified", "DB connection identity", "CockroachDB SQL role mapping", "data scope", "privileged-action constraints"))

    # ---------------- RoleMatrix
    ws = xl.add_sheet(wb, "RoleMatrix", hdr, mrows, widths=[34, 22, 9, 12, 9, 11, 8, 8, 11, 8, 20, 36] + [14] * len(S.ACTORS), freeze_cols=1)
    first = 13
    rng = f"{get_column_letter(first)}2:{get_column_letter(len(hdr))}{len(mrows) + 1}"
    fills = [("U", "FFE699"), ("D", "F4B084")]
    ws.conditional_formatting.add(rng, FormulaRule(formula=[f'ISNUMBER(SEARCH("D",LEFT({get_column_letter(first)}2,FIND("|",{get_column_letter(first)}2)-1)))'], fill=PatternFill("solid", bgColor="F4B084", fgColor="F4B084")))
    ws.conditional_formatting.add(rng, FormulaRule(formula=[f'ISNUMBER(SEARCH("U",LEFT({get_column_letter(first)}2,FIND("|",{get_column_letter(first)}2)-1)))'], fill=PatternFill("solid", bgColor="FFE699", fgColor="FFE699")))
    ws.conditional_formatting.add(rng, FormulaRule(formula=[f'LEFT({get_column_letter(first)}2,1)="-"'], font=Font(color="A6A6A6")))

    # ---------------- Rules
    rrows = []
    cnt = Counter(v["rule"] for v in rows.values())
    for rid, desc, owner, spec, tabs in S.GROUPS:
        rrows.append([rid, "explicit group", owner, desc, spec, cnt[rid], ", ".join(tabs[:8]) + (" ..." if len(tabs) > 8 else "")])
    dflt = [("RD-01", "default: lookups of internal modules (administration, ext_matching, ext_ads, analytics, ext_talent_ops, tier3_reference)", "platform", "LOOKUP_STAFF"),
            ("RD-02", "default: all other lookups (public reference values)", "public", "LOOKUP_PUBLIC"),
            ("RD-03", "default: master_data tables (countries, cities, skills, institutions ...): staff maintain, everybody reads", "platform", "MASTER_PUBLIC"),
            ("RD-04", "default: analytics tables that carry an organisation dimension: tenant-scoped reads through vw_*", "platform", "ANALYTICS_TENANT"),
            ("RD-05", "default: other analytics tables: staff dashboards only", "platform", "ANALYTICS_ADMIN")]
    for rid, desc, owner, tpl in dflt:
        rrows.append([rid, "module default", owner, desc, S.TPL[tpl], cnt[rid], ""])
    svc = [
        ("SR-01", "service rule", "app_service = union(human letters) + system writes (CRU / CR when append-only) on normal tables; SELECT only on money, session and ledger-kind tables; INSERT only on compliance vault; no access to AUTH and money-vault tables; no access to analytics."),
        ("SR-02", "service rule", "auth_svc: CRU on AUTH + SESSION tables (CR when append-only); RU on app_user and licence_seat; R on licence policy tables, app_user_role, user_block; CR on audit_event, security_event, error_log."),
        ("SR-03", "service rule", "billing_svc: CRU on money tables incl. money_ref tables (tables outside subscriptions_payments with an FK to wallet/ledger/payment_order/refund/invoice); R/RU/CR on the pricing catalogue; R on a fixed list of business tables it charges for (organisation, licence, job_requirement ...)."),
        ("SR-04", "service rule", "audit_writer: CR on audit_event/audit_chain_checkpoint/security_event/error_log, RU on audit_chain_head; membership granted to every writing tier (F-02)."),
        ("SR-05", "service rule", "purge_svc: R on policy tables; RU on app_user, data_subject_request, candidate_erasure_request; on person-owned (FK to candidate_profile/app_user/gig_worker_profile/consultant_profile or Personal/Sensitive columns) non-append-only tables: RUD for soft entities, RD for hard; none on append-only, ledger, config, analytics, master data."),
        ("SR-06", "service rule", "compliance_svc: CRU on COMPLIANCE_VAULT tables; R on user_consent and equal_opportunity_survey; staff have no access to the six compliance-only tables."),
        ("SR-07", "service rule", "etl_service: CRUD (CR if append-only) on analytics; CRU on tier3 snapshots; R on non-Sensitive business tables; R|V (pseudonymised view) when the table has Personal columns; none on AUTH/session/vault/compliance/message/note tables."),
        ("SR-08", "service rule", "analytics_reader: R on analytics tables (R|V when Personal columns, via vw_dim_*_current) and on tier3 snapshots; nothing on OLTP."),
        ("SR-09", "service rule", "audit_reader: R|V on audit_event, audit_chain_checkpoint, security_event, error_log, audit-kind history tables, audit_export, purge_job_run, user_status_history; lookups."),
        ("SR-10", "service rule", "backup_operator: no table privilege (N). migration_owner: CRU on lookups, master_data and feature flags (seeds); N elsewhere (DDL via schema_owner membership window)."),
        ("PF-01", "post filter", "Append-only tables: U and D are removed from every actor cell."),
        ("PF-02", "post filter", "Lookup tables: D is removed from every actor (retire with is_active)."),
        ("PF-03", "post filter", "COMPLIANCE_VAULT tables: human cells use the compliance service path (code A / V+A); six compliance-only tables have no staff access."),
        ("PF-04", "post filter", "A '-' cell drops the scope mark; it keeps the enforcement code that explains the denial (G for roles without a grant, A for personas without a permission)."),
        ("PF-05", "post filter", "Tables with Personal or Sensitive columns: persona pool roles (candidate, employer, recruiter, consultant, TPO, account_admin) never get a table-wide grant; G+A becomes V+A (reads through a viewer-scoped masked view, writes routed to app_service). Reason: a SQL injection on a persona pool must not expose a whole Personal table."),
    ]
    for rid, kind, desc in svc:
        rrows.append([rid, kind, "", desc, "", "", ""])
    xl.add_sheet(wb, "Rules", ["rule_id", "kind", "owner_scope", "rule / rationale", "human-actor cells (template spec)", "tables matched", "example tables"], rrows,
                 widths=[9, 14, 12, 90, 70, 9, 70], wrap_cols=("rule / rationale", "human-actor cells (template spec)", "example tables"))

    # ---------------- Enforcement
    xl.add_sheet(wb, "Enforcement", ["id", "actor / scope", "modules", "requirement (docket / rule)", "where and how it is enforced", "objects", "code", "CockroachDB capability / verification status", "B79 tests"],
                 X.ENFORCEMENT_ROWS, widths=[7, 24, 24, 42, 100, 40, 8, 48, 18],
                 wrap_cols=("actor / scope", "modules", "requirement (docket / rule)", "where and how it is enforced", "objects", "CockroachDB capability / verification status"))
    assert X.ENFORCEMENT_ROWS[26][0] == "E-27" and "owner" in X.ENFORCEMENT_ROWS[26][3].lower()

    # ---------------- Grants
    xl.add_sheet(wb, "Grants", ["id", "class / step", "role(s)", "statement template", "notes"], X.GRANT_ROWS, widths=[8, 24, 28, 120, 70], wrap_cols=("statement template", "notes", "role(s)"))

    # ---------------- AuditCoverage
    T_ = {t["name"]: t for t in model["tables"]}
    codes = {v["code"] for v in T_["audit_action"]["values"]}
    ents = {v["code"] for v in T_["audit_entity_type"]["values"]}
    arows, gap_codes, gap_ents = [], set(), set()
    for act, src, code, ent, evid, note in X.AUDIT_ROWS:
        if code:
            cs = "Covered" if code in codes else "GAP: add action code"
            if code not in codes: gap_codes.add(code)
        else:
            cs = "Covered by dedicated table/log (not audit_event)"
        if ent:
            es = "Yes" if ent in ents else "GAP: add entity type"
            if ent not in ents: gap_ents.add(ent)
        else:
            es = "n/a"
        arows.append([act, src, code, ent, evid, cs, es, note])
    for k, code, why in X.AUDIT_RECOMMENDATIONS:
        pass
    xl.add_sheet(wb, "AuditCoverage", ["sensitive action", "source / trigger", "audit_action.code", "audit_entity_type.code", "evidence rows", "action code status", "entity type status", "notes"],
                 arows, widths=[46, 38, 24, 26, 46, 26, 22, 60], wrap_cols=("sensitive action", "source / trigger", "evidence rows", "notes"), status_col="action code status")
    rec_rows = []
    for k, code, why in X.AUDIT_RECOMMENDATIONS:
        have = code in (codes if k == "audit_action" else ents)
        rec_rows.append([k, code, "already present" if have else "ADD (seed migration)", why])
    xl.add_sheet(wb, "AuditRecommend", ["lookup", "code to add", "status", "why"], rec_rows, widths=[20, 36, 24, 90], wrap_cols=("why",))
    gap_codes |= {c for k, c, w in X.AUDIT_RECOMMENDATIONS if k == "audit_action" and c not in codes}
    gap_ents |= {c for k, c, w in X.AUDIT_RECOMMENDATIONS if k == "audit_entity_type" and c not in ents}

    # ---------------- SensitiveColumns
    srows, masked, colgrant = [], [], 0
    readers = lambda n: ", ".join(a for a in S.ACTORS if "R" in C.split(rows[n]["cells"][a])[0])
    def method(col):
        p = (col.get("pii") or "").lower()
        if "argon2" in p: return "argon2id one-way hash"
        if "aes" in p: return "AES-256-GCM envelope encryption (app layer, KMS data key)"
        if "hmac" in p: return "keyed HMAC / blind index"
        if "sha-256" in p or "hash" in p: return "one-way hash of random token"
        if "vendor token" in p or "tokenis" in p or "token" in p: return "vendor token (no raw value stored)"
        if "vault reference" in p or "secret stored outside" in p: return "reference to external secret store"
        if "mask" in p: return "masked projection (view)"
        if "encrypt" in p: return "encryption at rest (storage layer)"
        return "access control + audit (masked view for non-owners)"
    for t in model["tables"]:
        n = t["name"]
        for c in t["columns"]:
            if c["sens"] in ("Sensitive", "Personal"):
                p = c.get("pii") or ""
                bad = bool(re.search(r"column[- ]?(level|grant|privilege|visible|access)", p, re.I))
                colgrant += bad
                srows.append([c["sens"], t["module"], n, c["name"], c["type"], c.get("domain", ""), method(c), p,
                              readers(n), t["delete_policy"], (t.get("retention") or "")[:160],
                              "FIX: no column-level GRANT in CockroachDB - use view / separate table (F-01)" if bad else ""])
        pcols = [c for c in t["columns"] if c["sens"] == "Personal"]
        scols = [c for c in t["columns"] if c["sens"] == "Sensitive"]
        if pcols or scols:
            incl = [c["name"] for c in t["columns"] if c["sens"] in ("Public", "Internal")]
            mk = [f"{c['name']} -> {masked_expr(c).format(c=c['name'])}" for c in pcols]
            vns = [a for a in S.HUMAN if "V" in C.split(rows[n]["cells"][a])[2] and C.split(rows[n]["cells"][a])[0] != "-"]
            masked.append([t["module"], n, f"vw_{n}_masked", f"vw_etl_{n}", ", ".join(vns), len(incl), ", ".join(incl), "; ".join(mk), ", ".join(c["name"] for c in scols)])
    cg_rules = [r["id"] for r in model["rules"] if re.search(r"column[- ]?(level|grant|privilege)", r["rule"] + r["mechanism"], re.I)]
    cg_views = [v["name"] for v in model["views"] if re.search(r"column[- ]?(level|grant|privilege)", (v.get("security") or "") + (v.get("purpose") or ""), re.I)]
    srows.sort(key=lambda r: (0 if r[0] == "Sensitive" else 1, r[1], r[2], r[3]))
    xl.add_sheet(wb, "SensitiveColumns", ["class", "module", "table", "column", "type", "domain", "protection method", "dictionary pii text", "actors with R on the table", "delete_policy", "retention (table)", "finding"],
                 srows, widths=[10, 22, 30, 28, 14, 14, 36, 70, 50, 12, 50, 40], wrap_cols=("dictionary pii text", "actors with R on the table", "retention (table)", "finding"), freeze_cols=0)
    xl.add_sheet(wb, "MaskedViews", ["module", "table", "persona/masked view", "ETL view", "personas reading via V", "# unmasked columns", "included columns (Public/Internal)", "masked Personal columns (expression)", "excluded Sensitive columns"],
                 masked, widths=[22, 30, 36, 36, 36, 9, 80, 80, 40], wrap_cols=("included columns (Public/Internal)", "masked Personal columns (expression)", "personas reading via V", "excluded Sensitive columns"))

    # ---------------- Tests
    xl.add_sheet(wb, "Tests_B79", ["id", "area", "actor", "test steps", "expected result", "evidence", "rule / BR"], TESTS, widths=[8, 20, 22, 80, 70, 40, 30], wrap_cols=("test steps", "expected result", "evidence", "rule / BR", "area"))

    # ---------------- Findings
    n_ao_personal = sum(1 for t in T.values() if t["delete_policy"] == "append_only" and any(c["sens"] in ("Personal", "Sensitive") for c in t["columns"]))
    frows = []
    for fid, sev, title, detail, rec in X.FINDINGS:
        frows.append([fid, sev, title, detail.format(n_rules=", ".join(cg_rules), n_views=", ".join(cg_views), n_colgrant=colgrant, n_ao_personal=n_ao_personal, n_gap_codes=len(gap_codes), n_gap_entities=len(gap_ents), n_masked=len(masked)),
                      rec.format(n_colgrant=colgrant, n_masked=len(masked))])
    xl.add_sheet(wb, "Findings", ["id", "severity", "finding", "detail", "recommendation"], frows, widths=[7, 9, 50, 90, 90], wrap_cols=("finding", "detail", "recommendation"))

    # ---------------- Validation
    vrows = [[c, r, d] for c, r, d in results]
    ao = [n for n, t in T.items() if t["delete_policy"] == "append_only"]
    vrows.append(["Actor cell counts (any privilege)", "INFO", "; ".join(f"{a}: {sum(1 for n in T if C.split(rows[n]['cells'][a])[0] != '-')}" for a in S.ACTORS)])
    vrows.append(["Tables per grant_class", "INFO", "; ".join(f"{k}: {v}" for k, v in sorted(Counter(r['gclass'] for r in rows.values()).items()))])
    vrows.append(["Tables per rule id (top 5)", "INFO", "; ".join(f"{k}: {v}" for k, v in cnt.most_common(5))])
    vrows.append(["Append-only tables", "INFO", f"{len(ao)}"])
    ws = xl.add_sheet(wb, "Validation", ["check", "result", "detail"], vrows, widths=[90, 10, 100], wrap_cols=("check", "detail"))
    for r in range(2, ws.max_row + 1):
        v = ws.cell(row=r, column=2).value
        ws.cell(row=r, column=2).fill = PatternFill("solid", fgColor={"PASS": "C6EFCE", "FAIL": "FFC7CE", "INFO": "DDEBF7"}.get(v, "FFFFFF"))

    # sheet order
    order = ["Legend", "Actors", "RoleMatrix", "Rules", "Enforcement", "Grants", "AuditCoverage", "AuditRecommend", "SensitiveColumns", "MaskedViews", "Tests_B79", "Findings", "Validation"]
    wb._sheets = [wb[n] for n in order]
    wb.save(OUT)
    fails = [r for r in results if r[1] == "FAIL"]
    print(f"wrote {OUT}: {len(mrows)} tables x {len(S.ACTORS)} actors; validation fails: {len(fails)}")
    for r in fails: print("  FAIL", r)
    print("gap codes:", sorted(gap_codes), "gap entities:", sorted(gap_ents), "colgrant:", colgrant, "ao_personal:", n_ao_personal, "masked views:", len(masked))
    return model, T, rows, dict(colgrant=colgrant, n_ao_personal=n_ao_personal, gap_codes=sorted(gap_codes), gap_ents=sorted(gap_ents), n_masked=len(masked))


if __name__ == "__main__":
    main()
